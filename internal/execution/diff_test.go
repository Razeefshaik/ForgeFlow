func TestRuntimeExcludesGeneratedCachesOnce(t *testing.T) {
	s, c := buildFixture(t, &fixtureRunner{})
	repo, _, err := s.Paths(c)
	if err != nil {
		t.Fatal(err)
	}
	exclude := filepath.Join(repo, ".git", "info", "exclude")
	// An existing workspace prepared before cache patterns were added.
	if err = os.WriteFile(exclude, []byte("# local\r\n/.forgeflow-runtime/\r\n"), 0600); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 2; i++ {
		if err = s.prepareRuntime(repo); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(exclude)
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.ReplaceAll(string(b), "\r", ""), "\n")
	for _, pattern := range append([]string{"/.forgeflow-runtime/", "# local"}, generatedCachePatterns...) {
		count := 0
		for _, line := range lines {
			if line == pattern {
				count++
			}
		}
		if count != 1 {
			t.Fatalf("pattern %q appears %d times:\n%s", pattern, count, b)
		}
	}
}

func TestDiffListsBinaryAndLargeUntrackedFilesAcrossPRCommit(t *testing.T) {
	s, c := buildFixture(t, &fixtureRunner{})
	repo, _, err := s.Paths(c)
	if err != nil {
		t.Fatal(err)
	}
	if err = s.prepareRuntime(repo); err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	write := func(name string, body []byte) {
		t.Helper()
		path := filepath.Join(repo, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, body, 0600); err != nil {
			t.Fatal(err)
		}
	}
	// The 2026-10-17 failure: host Python wrote bytecode for a new test.
	pyc := append([]byte{0xcb, 0x0d, 0x0d, 0x0a, 0, 0, 0, 0}, bytes.Repeat([]byte{0xe3, 0}, 64)...)
	write("tests/__pycache__/test_handbooks.cpython-313.pyc", pyc)
	write("tests/test_handbooks.py", []byte("def test_handbooks():\n    assert True\n"))
	write("assets/logo.bin", append([]byte("\x89PNG\r\n\x1a\n\x00\x00\x00\rIHDR"), bytes.Repeat([]byte{1, 0, 2}, 100)...))
	large := bytes.Repeat([]byte("generated fixture line\n"), (300<<10)/23)
	write("testdata/large.txt", large)
	write("sum.go", []byte("package fixture\nfunc Add(a,b int) int {return a+b}\n"))

	diff, files, err := s.diff(ctx, repo, c.BaseCommit)
	if err != nil {
		t.Fatal("finished patch was refused:", err)
	}
	if strings.Join(files, ",") != "assets/logo.bin,sum.go,testdata/large.txt,tests/test_handbooks.py" {
		t.Fatal("changed files", files)
	}
	if strings.Contains(diff, "__pycache__") {
		t.Fatal("generated bytecode reached the patch", diff)
	}
	blob, err := s.git(ctx, repo, "hash-object", "--no-filters", "--", "assets/logo.bin")
	if err != nil {
		t.Fatal(err)
	}
	binaryNote := "diff --git a/assets/logo.bin b/assets/logo.bin\nnew file mode 100644\nindex " + strings.Repeat("0", 40) + ".." + strings.TrimSpace(blob) + "\nBinary files /dev/null and b/assets/logo.bin differ\n"
	if !strings.Contains(diff, binaryNote) {
		t.Fatal("binary file is not represented with its full blob ID", diff)
	}
	if !strings.Contains(diff, "diff --git a/testdata/large.txt b/testdata/large.txt\nnew file mode 100644\n") || !strings.Contains(diff, "Contents omitted, "+strconv.Itoa(len(large))+" bytes") || strings.Contains(diff, "+generated fixture line") {
		t.Fatal("large text file was inlined or not listed", len(diff))
	}
	if !strings.Contains(diff, "+def test_handbooks():") || !strings.Contains(diff, "+func Add(a,b int) int {return a+b}") {
		t.Fatal("ordinary changes lost", diff)
	}

	// Same-size binary edits must still change the reviewed patch hash.
	changed := append([]byte("\x89PNG\r\n\x1a\n\x00\x00\x00\rIHDR"), bytes.Repeat([]byte{1, 0, 3}, 100)...)
	write("assets/logo.bin", changed)
	if edited, _, err := s.diff(ctx, repo, c.BaseCommit); err != nil || contextHash(edited) == contextHash(diff) {
		t.Fatal("binary content change did not change the patch", err)
	}
	write("assets/logo.bin", append([]byte("\x89PNG\r\n\x1a\n\x00\x00\x00\rIHDR"), bytes.Repeat([]byte{1, 0, 2}, 100)...))

	// PR preparation stages with the same ignore rules and commits exactly the
	// reviewed files; the canonical diff is unchanged by that commit.
	if _, err = s.git(ctx, repo, "add", "--all", "--", "."); err != nil {
		t.Fatal(err)
	}
	if _, err = s.git(ctx, repo, "-c", "user.name=ForgeFlow", "-c", "user.email=forgeflow@localhost", "-c", "commit.gpgsign=false", "commit", "-m", "Fixture"); err != nil {
		t.Fatal(err)
	}
	committed, err := s.git(ctx, repo, "diff", "--name-only", "-z", c.BaseCommit, "HEAD")
	if err != nil || strings.Join(strings.Split(strings.TrimSuffix(committed, "\x00"), "\x00"), ",") != strings.Join(files, ",") {
		t.Fatalf("PR commit differs from reviewed files: %q %v", committed, err)
	}
	after, afterFiles, err := s.diff(ctx, repo, c.BaseCommit)
	if err != nil || after != diff || strings.Join(afterFiles, ",") != strings.Join(files, ",") {
		t.Fatal("reviewed diff changed when binary and large files were committed", err)
	}
	gitNote, err := s.git(ctx, repo, "diff", "--no-ext-diff", "--full-index", c.BaseCommit, "--", "assets/logo.bin")
	if err != nil || gitNote != binaryNote {
		t.Fatalf("binary note differs from Git's own rendering (%v):\n%s\n%s", err, gitNote, binaryNote)
	}
}

func TestDiffStillRefusesLinkedFiles(t *testing.T) {
	s, c := buildFixture(t, &fixtureRunner{})
	repo, _, err := s.Paths(c)
	if err != nil {
		t.Fatal(err)
	}
	if err = s.prepareRuntime(repo); err != nil {
		t.Fatal(err)
	}
	if err = os.Symlink(filepath.Join(repo, "sum.go"), filepath.Join(repo, "linked.go")); err != nil {
		t.Skip("symbolic links unavailable:", err)
	}
	if _, _, err = s.diff(context.Background(), repo, c.BaseCommit); err == nil || !strings.Contains(err.Error(), "linked") {
		t.Fatal("linked untracked file was accepted", err)
	}
}

func TestGitPathQuotesUnusualNames(t *testing.T) {
	for name, want := range map[string]string{"plain dir/file.bin": "b/plain dir/file.bin", "new\nline": `"b/new\012line"`, "café": `"b/caf\303\251"`, `a"b`: `"b/a\"b"`} {
		if got := gitPath("b/", name); got != want {
			t.Errorf("%q: got %s want %s", name, got, want)
		}
	}
}
